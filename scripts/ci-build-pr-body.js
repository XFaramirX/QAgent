#!/usr/bin/env node
'use strict';

/**
 * ci-build-pr-body.js
 *
 * Generates the pull request body for an automated QA PR.
 * Reads artifacts from the ticket directory and prints the body to stdout.
 *
 * Usage:
 *   node scripts/ci-build-pr-body.js <ticketId> <issueNumber> <runId>
 *
 * Output is piped to a file in issue-to-qa.yml:
 *   node scripts/ci-build-pr-body.js QA-007 42 12345678 > pr_body.md
 */

const fs   = require('fs');
const path = require('path');

const [,, ticketId, issueNumber, runId] = process.argv;

const repoRoot  = path.resolve(__dirname, '..');
const ticketDir = path.join(repoRoot, 'tickets', ticketId || 'UNKNOWN');

function readSafe(p) {
  try { return fs.readFileSync(p, 'utf8'); } catch { return null; }
}

function parseJSON(p) {
  const raw = readSafe(p);
  if (!raw) return null;
  try { return JSON.parse(raw); } catch { return null; }
}

// ── Read artifacts ────────────────────────────────────────────────────────────

const analysis = parseJSON(path.join(ticketDir, 'analysis.json'));
const status   = parseJSON(path.join(ticketDir, 'logs', 'status.json'));
const results  = parseJSON(path.join(ticketDir, 'results', 'summary.json'));

const generatedDir = path.join(ticketDir, 'generated');
const specFiles = fs.existsSync(generatedDir)
  ? fs.readdirSync(generatedDir).filter(f => f.endsWith('.spec.ts'))
  : [];

// ── Build sections ────────────────────────────────────────────────────────────

const scenarioList = analysis?.scenarios?.length
  ? analysis.scenarios
      .map(s => `- \`${s.id || '?'}\` — ${s.title || s.name || s.description || 'Unnamed'}`)
      .join('\n')
  : '_No scenarios extracted_';

const testResultBlock = results
  ? `\`\`\`\npassed: ${results.passed ?? '?'}  failed: ${results.failed ?? '?'}  total: ${results.total ?? '?'}\n\`\`\``
  : '_Tests not yet run_';

const snapshotLink = analysis?.snapshotRef
  ? `[\`${analysis.snapshotRef}\`](${analysis.snapshotRef}/snapshot.md)`
  : '_No snapshot captured_';

const specList = specFiles.length
  ? specFiles.map(f => `- \`tickets/${ticketId}/generated/${f}\``).join('\n')
  : '_No spec files generated_';

const analystStatus   = status?.['requirement-analyst']?.status  ?? 'unknown';
const generatorStatus = status?.['playwright-generator']?.status ?? 'unknown';
const runUrl = process.env.GITHUB_SERVER_URL && process.env.GITHUB_REPOSITORY
  ? `${process.env.GITHUB_SERVER_URL}/${process.env.GITHUB_REPOSITORY}/actions/runs/${runId}`
  : null;

// ── Compose body ──────────────────────────────────────────────────────────────

const body = `<!-- AUTO-GENERATED by QA Pipeline — edit with care -->
## 🤖 QA Automated PR — \`${ticketId}\`

> **Closes** #${issueNumber || '?'}

---

### Ticket Reference

| Field | Value |
|-------|-------|
| Ticket ID | \`${ticketId}\` |
| Feature | ${analysis?.feature || '_Unknown_'} |
| Target URL | ${analysis?.targetUrl || analysis?.['target-url'] || '_See ticket.md_'} |
| Source Issue | #${issueNumber || '?'} |
| Pipeline run | ${runUrl ? `[${runId}](${runUrl})` : `\`${runId || 'n/a'}\``} |

---

### Analysis Summary

${analysis?.summary || '_See `tickets/' + ticketId + '/analysis.json` for full details._'}

**Scenarios (${analysis?.scenarios?.length ?? 0}):**
${scenarioList}

**Snapshot evidence:** ${snapshotLink}

---

### Generated Tests

${specList}

**Test run results:**
${testResultBlock}

---

### Traceability

| Artifact | Status |
|----------|--------|
| \`ticket.md\` | ✅ |
| \`analysis.json\` | ${analysis ? '✅' : '❌ Missing'} |
| \`approved-analysis.json\` | ⏳ Pending human review |
| Spec file(s) in \`generated/\` | ${specFiles.length > 0 ? '✅' : '⚠️ None generated'} |
| Requirement Analyst | ${analystStatus === 'completed' ? '✅ completed' : analystStatus} |
| Playwright Generator | ${generatorStatus === 'completed' ? '✅ completed' : generatorStatus} |
| Snapshot captured | ${analysis?.snapshotRef ? '✅' : '⚠️ No snapshot'} |

---

### Reviewer Checklist

**Analysis quality**
- [ ] Acceptance criteria correctly extracted from the ticket
- [ ] No invented business rules, error messages, or field constraints
- [ ] Ambiguities recorded in \`analysis.json → questions\`
- [ ] Risks noted in \`analysis.json → risks\`

**Test quality**
- [ ] Locators come from the snapshot (role/label/placeholder preferred)
- [ ] No brittle XPath, \`nth-child\`, or randomly generated class selectors
- [ ] Every \`test.skip()\` has a clear, documented reason
- [ ] Assertions are meaningful
- [ ] No \`page.waitForTimeout()\` calls

**Safety**
- [ ] No credentials, tokens, or PII in test data
- [ ] Tests are idempotent (safe to re-run)

**Sign-off**
- [ ] Copy \`analysis.json\` → \`approved-analysis.json\` once satisfied with the analysis

---

_Generated by QA Pipeline · Agents: Requirement Analyst + Playwright Generator · Model: \`${process.env.QA_AI_MODEL || 'openai/gpt-4o'}\`_
`;

process.stdout.write(body);
